import type { Field } from "@letters-patent/schema";
import type { Core, Issuer, OutputFile } from "./types";

import { entries } from "objectively";

import { RESOURCE } from "./constant";
import { describe } from "./describe";
import { CLAIM_TYPES } from "./standard";
import { json } from "./util";

/** The banner at the top of every emitted module. It names the resource of the build. */
const banner = (core: Core): string =>
  `// Generated by @letters-patent/kit from ${JSON.stringify(
    core.resource?.resource ?? "letters-patent",
  )}. Do not edit by hand.`;

/** A string-literal union with one member per line, or `never` when empty. It follows a bare `=`. */
const union = (members: readonly (string | number)[]): string => {
  if (members.length === 0) {
    return " never";
  }
  return members.map((member) => `\n  | ${JSON.stringify(member)}`).join("");
};

/** A readonly tuple of literals. */
const tuple = (values: readonly (string | number)[]): string =>
  `readonly [${values.map((value) => JSON.stringify(value)).join(", ")}]`;

/** The type literal of one meta field declaration. */
const declaration = (field: Field): string => {
  if (typeof field === "string") {
    return JSON.stringify(field);
  }
  if (Array.isArray(field)) {
    return tuple(field as readonly (string | number)[]);
  }
  const choice = field as {
    values: readonly (string | number)[];
    optional?: boolean;
  };
  const optional = choice.optional ? "; readonly optional: true" : "";
  return `{ readonly values: ${tuple(choice.values)}${optional} }`;
};

/**
 * Makes a module and its declarations as two files. TypeScript pairs a
 * `.d.mts` file with an `.mjs` file under every module resolution.
 */
const pair = (name: string, mjs: string[], dts: string[]): OutputFile[] => [
  { path: `${name}.mjs`, contents: `${mjs.join("\n")}\n` },
  { path: `${name}.d.mts`, contents: `${dts.join("\n")}\n` },
];

/** The vocabularies, with the singular type name each declares. */
const VOCABULARIES = [
  ["scopes", "Scope"],
  ["roles", "Role"],
  ["groups", "Group"],
  ["entitlements", "Entitlement"],
] as const;

/**
 * Makes the root entry: the vocabulary lists, their guards, and the literal
 * unions every other declaration uses.
 */
const index = (core: Core): OutputFile[] => {
  const { contract } = core;
  return pair(
    "index",
    [
      banner(core),
      ...VOCABULARIES.map(
        ([plural]) =>
          `export const ${plural} = Object.freeze(${json(contract[plural])});`,
      ),
      `const known = { ${VOCABULARIES.map(
        ([plural]) => `${plural}: new Set(${plural})`,
      ).join(", ")} };`,
      ...VOCABULARIES.map(
        ([plural, singular]) =>
          `export const is${singular} = (value) => typeof value === "string" && known.${plural}.has(value);`,
      ),
    ],
    [
      banner(core),
      ...VOCABULARIES.map(
        ([plural, singular]) =>
          `export type ${singular} =${union(contract[plural])};`,
      ),
      ...VOCABULARIES.map(
        ([plural, singular]) =>
          `export declare const ${plural}: readonly ${singular}[];`,
      ),
      ...VOCABULARIES.map(
        ([, singular]) =>
          `export declare const is${singular}: (value: unknown) => value is ${singular};`,
      ),
    ],
  );
};

/**
 * Makes the `./config` entry: the contract as data, and the `Contract`
 * type with every literal — what `defineSchema` and the service are
 * parameterized by.
 */
const config = (core: Core): OutputFile[] => {
  const { contract } = core;
  const meta = entries(contract.meta).map(
    ([key, field]) => `    ${JSON.stringify(key)}: ${declaration(field)};`,
  );
  return pair(
    "config",
    [
      banner(core),
      `export const contract = ${json(contract)};`,
      "export default { contract };",
    ],
    [
      banner(core),
      'import type { Meta as PatentMeta, User as PatentUser } from "letters-patent";',
      "export type Contract = {",
      ...VOCABULARIES.map(
        ([plural]) => `  ${plural}: ${tuple(contract[plural])};`,
      ),
      meta.length === 0 ? "  meta: {};" : `  meta: {\n${meta.join("\n")}\n  };`,
      "};",
      "export type Meta = PatentMeta<Contract>;",
      "export type User = PatentUser<Meta>;",
      "export declare const contract: Contract;",
      "declare const config: { readonly contract: Contract };",
      "export default config;",
    ],
  );
};

/**
 * Makes the `./manifest` entry: each vocabulary member and each requested
 * claim with an id, a name, and a description, for an interface.
 */
const manifest = (core: Core): OutputFile[] =>
  pair(
    "manifest",
    [
      banner(core),
      `export const manifest = ${json(core.manifest ?? describe(core.contract))};`,
      "export default manifest;",
    ],
    [
      banner(core),
      'import type { Entitlement, Group, Role, Scope } from "./index.mjs";',
      "export interface Entry<Id extends string = string> {",
      "  readonly id: Id;",
      "  readonly name: string;",
      "  readonly description?: string;",
      "}",
      "export interface ClaimEntry extends Entry {",
      "  readonly essential: boolean;",
      "  readonly values?: readonly (string | number)[];",
      "}",
      "export interface Manifest {",
      "  readonly scopes: readonly Entry<Scope>[];",
      "  readonly roles: readonly Entry<Role>[];",
      "  readonly groups: readonly Entry<Group>[];",
      "  readonly entitlements: readonly Entry<Entitlement>[];",
      "  readonly claims: readonly ClaimEntry[];",
      "}",
      "export declare const manifest: Manifest;",
      "export default manifest;",
    ],
  );

/**
 * The `Claims` interface of one issuer: every claim in `claims_supported`
 * with its registered type, `sub` required, anything else the issuer may
 * add reachable as `unknown`.
 */
const claims = (issuer: Issuer): string[] => {
  const members = issuer.claims
    .filter((claim) => claim !== "sub")
    .map((claim) => `  ${claim}?: ${CLAIM_TYPES[claim] ?? "unknown"};`);
  return [
    `/** The claims ${issuer.issuer} publishes (\`claims_supported\`). */`,
    "export interface Claims {",
    "  sub: string;",
    ...members,
    "  [claim: string]: unknown;",
    "}",
  ];
};

/** A `readonly` object type literal over string members. */
const literal = (members: Record<string, string>): string =>
  `{ ${entries(members)
    .map(([key, type]) => `readonly ${key}: ${type}`)
    .join("; ")} }`;

/**
 * Makes the issuer files: one module per issuer with its endpoints and
 * capabilities as literals, and the `./issuers` entry listing them.
 */
const issuers = (core: Core): OutputFile[] => {
  const built = core.issuers ?? [];
  const files = built.flatMap((issuer) =>
    pair(
      `issuers/${issuer.id}`,
      [
        banner(core),
        `export const issuer = ${json(issuer)};`,
        "export default issuer;",
      ],
      [
        banner(core),
        ...claims(issuer),
        "export declare const issuer: {",
        `  readonly id: ${JSON.stringify(issuer.id)};`,
        `  readonly issuer: ${JSON.stringify(issuer.issuer)};`,
        `  readonly endpoints: ${literal(
          Object.fromEntries(
            Object.keys(issuer.endpoints).map((key) => [key, "string"]),
          ),
        )};`,
        `  readonly caps: ${literal(
          Object.fromEntries(
            entries(issuer.caps).map(([key, value]) => [key, String(value)]),
          ),
        )};`,
        `  readonly scopes: ${tuple(issuer.scopes)};`,
        `  readonly claims: ${tuple(issuer.claims)};`,
        "};",
        "export type Issuer = typeof issuer;",
        "export default issuer;",
      ],
    ),
  );
  const list = built.map(({ id, issuer }) => ({ id, issuer }));
  return [
    ...files,
    ...pair(
      "issuers",
      [
        banner(core),
        `export const issuers = ${json(list)};`,
        "export default issuers;",
      ],
      [
        banner(core),
        `export type IssuerId =${union(list.map((entry) => entry.id))};`,
        "export interface IssuerEntry {",
        "  readonly id: IssuerId;",
        "  readonly issuer: string;",
        "}",
        "export declare const issuers: readonly IssuerEntry[];",
        "export default issuers;",
      ],
    ),
  ];
};

/** Makes `resource.json`, when the build has the resource document. */
const resource = (core: Core): OutputFile[] =>
  core.resource === undefined
    ? []
    : [{ path: RESOURCE, contents: `${json(core.resource)}\n` }];

/**
 * Emits every file of a build.
 *
 * - `index` has the `Scope`, `Role`, `Group`, and `Entitlement` types, the
 *   vocabulary lists, and the `isScope`, `isRole`, `isGroup`, and
 *   `isEntitlement` guards.
 * - `config` has the contract and the `Contract`, `Meta`, and `User` types.
 * - `manifest` has each vocabulary member and requested claim with its id,
 *   name, and description.
 * - `issuers/<id>` is one issuer's endpoints, capabilities, and `Claims`
 *   type; `issuers` lists them.
 * - `resource.json` is the Protected Resource Metadata, ready to serve.
 *
 * Each module is an `.mjs` file with a `.d.mts` file beside it. The
 * function takes a {@link Core}: a consumer that holds only a contract, such
 * as a framework module, emits the same modules the CLI writes.
 */
export const emit = (core: Core): OutputFile[] => [
  ...index(core),
  ...config(core),
  ...manifest(core),
  ...issuers(core),
  ...resource(core),
];
